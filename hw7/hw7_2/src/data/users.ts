// Імпортуємо тільки тип — у зібраний JS він не потрапить (verbatimModuleSyntax)
import type {IUser} from '../models/IUser.ts';

// Базові імена, з яких складемо великий список
const NAMES = ['Олена', 'Андрій', 'Марія', 'Тарас', 'Ірина', 'Богдан', 'Софія', 'Дмитро', 'Катерина', 'Остап'];

// 5000 користувачів — достатньо, щоб фільтр + сортування були помітно "дорогими"
export const users: IUser[] = Array.from({length: 5000}, (_, i) => ({
    id: i + 1,                                        // id від 1 до 5000
    name: `${NAMES[i % NAMES.length]} #${i + 1}`,     // наприклад "Марія #3"
    age: 18 + ((i * 37) % 50),                        // псевдовипадковий вік 18–67
}));
